from __future__ import annotations

import logging
import tempfile
from pathlib import Path
from typing import Any

import webvtt

from config.settings import AppSettings
from src.storage.base import StorageFile, StorageProvider
from src.vtt_builder import VTTBuilder

logger = logging.getLogger(__name__)

VIDEO_EXTENSIONS = {".mp4", ".mkv", ".mov", ".wmv", ".avi", ".webm"}
TIMESTAMP_EPSILON = 0.001


def validate_vtt_file(path: Path) -> tuple[list[dict[str, Any]], list[str]]:
    """Read a VTT and return its cues plus validation errors without raising."""
    errors: list[str] = []
    try:
        parsed = webvtt.read(str(path))
    except Exception as exc:
        return [], [f"invalid VTT syntax: {exc}"]

    segments: list[dict[str, Any]] = []
    previous_start = -1.0
    for index, caption in enumerate(parsed, start=1):
        start = float(caption.start_in_seconds)
        end = float(caption.end_in_seconds)
        text = caption.text.strip()
        segments.append({"start": start, "end": end, "text": text})
        if start < 0:
            errors.append(f"cue {index}: negative start")
        if end <= start:
            errors.append(f"cue {index}: end ({end:.3f}) must be greater than start ({start:.3f})")
        if start + TIMESTAMP_EPSILON < previous_start:
            errors.append(f"cue {index}: timestamps are not ordered")
        previous_start = start

    if not segments:
        errors.append("no cues found")
    return segments, errors


def _valid_segments(segments: list[dict[str, Any]]) -> bool:
    if not segments:
        return False
    try:
        VTTBuilder.validate_segments(segments)
    except (KeyError, TypeError, ValueError):
        return False
    return True


def _pick(files: list[StorageFile], *, original: bool) -> StorageFile | None:
    vtts = [
        item
        for item in files
        if not item.is_directory
        and Path(item.name).suffix.lower() == ".vtt"
        and ".bak." not in item.name.lower()
    ]
    if original:
        preferred = [item for item in vtts if "_original" in item.name.lower()]
    else:
        preferred = [item for item in vtts if "_original" not in item.name.lower()]
    return (
        sorted(
            preferred or vtts,
            key=lambda item: item.name.lower(),
        )[0]
        if (preferred or vtts)
        else None
    )


def _next_backup(storage: StorageProvider, parent: str, name: str) -> str:
    index = 0
    while True:
        suffix = ".bak" if index == 0 else f".bak.{index:02d}"
        candidate = f"{name}{suffix}"
        if not storage.file_exists(parent, candidate):
            return candidate
        index += 1


def _backup_replace(
    storage: StorageProvider,
    current: StorageFile | None,
    parent: str,
    replacement: Path,
) -> str | None:
    backup_name = None
    if current:
        with tempfile.TemporaryDirectory(prefix="vtt-backup-") as temp_dir:
            backup_path = Path(temp_dir) / current.name
            storage.download_file(current, backup_path)
            backup_name = _next_backup(storage, parent, current.name)
            backup_target = backup_path.with_name(backup_name)
            backup_target.write_bytes(backup_path.read_bytes())
            storage.upload_file(backup_target, parent, "text/vtt")
    target_name = current.name if current else replacement.name
    named = replacement.with_name(target_name)
    storage.upload_file(named, parent, "text/vtt")
    return backup_name


def repair_output_subtitles(
    storage: StorageProvider,
    settings: AppSettings,
    output_folder: str,
) -> dict[str, Any]:
    """Repair invalid/missing original or translated VTTs using the existing video.

    There are three supported recovery paths:
    1. original STT VTT invalid/missing -> rerun STT on the existing video, then translate;
    2. original valid but translated VTT invalid/missing -> reuse original timings and retranslate;
    3. both invalid -> rerun STT once, then translate the regenerated cues.

    A valid original VTT is never replaced, and a valid translated VTT is never
    regenerated. The existing MP4/WebM is never regenerated by this helper.
    """
    children = [item for item in storage.list_children(output_folder) if not item.is_directory]
    video = next(
        (item for item in children if Path(item.name).suffix.lower() == ".mp4" and "_tts" not in item.name.lower()),
        None,
    )
    if video is None:
        video = next(
            (
                item
                for item in children
                if Path(item.name).suffix.lower() in VIDEO_EXTENSIONS and "_tts" not in item.name.lower()
            ),
            None,
        )
    if video is None:
        return {"status": "skipped", "reason": "no reusable source video"}

    original_dir = storage.ensure_folder(
        output_folder,
        settings.original_transcript_subdir,
    )
    original_files = [item for item in storage.list_children(original_dir) if not item.is_directory]
    original = _pick(original_files, original=True)
    translated = _pick(children, original=False)

    with tempfile.TemporaryDirectory(prefix="subtitle-repair-") as temp_dir:
        root = Path(temp_dir)
        video_path = root / video.name
        storage.download_file(video, video_path)

        original_segments: list[dict[str, Any]] = []
        original_errors = ["missing original VTT"]
        if original is not None:
            original_path = root / original.name
            storage.download_file(original, original_path)
            original_segments, original_errors = validate_vtt_file(original_path)

        translated_segments: list[dict[str, Any]] = []
        translated_errors = ["missing translated VTT"]
        if translated is not None:
            translated_path = root / translated.name
            storage.download_file(translated, translated_path)
            translated_segments, translated_errors = validate_vtt_file(translated_path)

        original_repaired = bool(original_errors)
        translated_repaired = bool(translated_errors)
        backups: list[str] = []

        if original_repaired:
            logger.warning(
                "Repairing original VTT for %s: %s",
                output_folder,
                "; ".join(original_errors),
            )
            from src.stt_engine import STTEngine

            segments = STTEngine(settings).transcribe(video_path)
            if not _valid_segments(segments):
                raise ValueError("STT produced invalid subtitle timestamps during repair")
            repaired_original = root / f"{Path(video.name).stem}_original.vtt"
            VTTBuilder.generate_vtt(segments, repaired_original)
            backups.append(
                _backup_replace(
                    storage,
                    original,
                    original_dir,
                    repaired_original,
                )
                or ""
            )
            original_segments = segments
            translated_repaired = True

        if translated_repaired:
            if not _valid_segments(original_segments):
                raise ValueError("Cannot repair translated VTT without a valid original transcription")
            logger.warning(
                "Repairing translated VTT for %s: %s",
                output_folder,
                "; ".join(translated_errors) if translated_errors else "original VTT was regenerated",
            )
            from src.translator import TextTranslator

            translated_segments = TextTranslator(settings).translate_segments(original_segments)
            if not _valid_segments(translated_segments):
                raise ValueError("Translation produced invalid subtitle timestamps during repair")
            target_name = (
                translated.name
                if translated is not None
                else f"{Path(video.name).stem}_{settings.target_lang.lower()}.vtt"
            )
            repaired_translated = root / target_name
            VTTBuilder.generate_vtt(translated_segments, repaired_translated)
            backups.append(
                _backup_replace(
                    storage,
                    translated,
                    output_folder,
                    repaired_translated,
                )
                or ""
            )

        status = "repaired" if original_repaired or translated_repaired else "valid"
        return {
            "status": status,
            "output_folder": output_folder,
            "video": video.name,
            "original_repaired": original_repaired,
            "translated_repaired": translated_repaired,
            "original_errors": original_errors if original_repaired else [],
            "translated_errors": translated_errors if translated_repaired else [],
            "backups": [item for item in backups if item],
            "stt_regenerated": original_repaired,
            "video_regenerated": False,
        }
